-- Table used by lib/pastes.ts. Run in the Supabase SQL editor.
-- Column names are quoted because the app uses camelCase.
create table if not exists public."Pastes" (
  id bigint generated by default as identity primary key,
  "pasteId" text not null unique,
  code text not null,
  title text,
  description text,
  language text,
  public boolean default false,
  private boolean default false,
  "createdAt" timestamptz not null default now(),
  "userId" text,
  "pastePassword" text,
  "hasVanity" boolean default false
);

create index if not exists "Pastes_userId_idx" on public."Pastes" ("userId");
create index if not exists "Pastes_public_createdAt_idx"
  on public."Pastes" ("createdAt" desc) where public;

-- All access goes through the server with SUPABASE_SECRET_KEY, which bypasses
-- RLS. With no policies, the publishable key can't read or write anything.
alter table public."Pastes" enable row level security;

notify pgrst, 'reload schema';
